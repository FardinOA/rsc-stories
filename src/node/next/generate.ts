import { existsSync, readFileSync } from 'node:fs';
import { lstat, mkdir, readdir, readFile, rm, symlink, writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { RenderMode } from '../../shared/global';
import type { StoryIndex } from '../indexer';
import type { Project } from '../project';
import type { WorkshopNextConfigOptions } from './next-config';
import { exportNames, readDirective, resolveSpecifier } from './resolve';
import { workshopTsconfig } from './tsconfig';

/** Result of generating the workshop app. */
export interface GenerateResult {
  /** Specifier → absolute shim path, as configured in the bundler. */
  aliases: Record<string, string>;
  warnings: string[];
  /** `true` when next.config or tsconfig changed and a running Next must restart. */
  configChanged: boolean;
}

function posix(value: string): string {
  return value.split(path.sep).join('/');
}

/** Relative import specifier from `fromFile` to `toFile`, extension dropped for TS sources. */
function importPath(fromFile: string, toFile: string): string {
  let relative = posix(path.relative(path.dirname(fromFile), toFile));
  relative = relative.replace(/\.(tsx?|jsx?|mts|mjs)$/, '');
  return relative.startsWith('.') ? relative : `./${relative}`;
}

async function writeIfChanged(file: string, content: string): Promise<boolean> {
  try {
    if ((await readFile(file, 'utf8')) === content) return false;
  } catch {
    // New file.
  }
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, content);
  return true;
}

function slug(specifier: string): string {
  return (
    specifier
      .replace(/^@/, '')
      .replace(/[^a-zA-Z0-9]+/g, '-')
      .replace(/^-|-$/g, '') || 'module'
  );
}

const BANNER = '// Generated by rsc-stories. Do not edit; regenerated on every start.\n';

/** Export names of `next/cache` for the installed Next version. */
function nextCacheExports(project: Project): string[] {
  try {
    const source = readFileSync(path.join(project.next.packageDir, 'cache.js'), 'utf8');
    const names = new Set<string>();
    for (const match of source.matchAll(/^exports\.([A-Za-z_$][\w$]*)\s*=/gm)) names.add(match[1]!);
    return [...names];
  } catch {
    return ['unstable_cache', 'revalidatePath', 'revalidateTag', 'unstable_noStore'];
  }
}

function hasNavigationPromisesContext(project: Project): boolean {
  try {
    const source = readFileSync(path.join(project.next.packageDir, 'dist/shared/lib/hooks-client-context.shared-runtime.d.ts'), 'utf8');
    return source.includes('NavigationPromisesContext');
  } catch {
    return false;
  }
}

function hostUsesCacheComponents(project: Project): boolean {
  if (!project.nextConfigFile) return false;
  try {
    return /cacheComponents\s*:\s*true|dynamicIO\s*:\s*true/.test(readFileSync(project.nextConfigFile, 'utf8'));
  } catch {
    return false;
  }
}

async function moduleShims(
  project: Project,
  index: StoryIndex,
  shimDir: string,
  warnings: string[],
  realFiles: Record<string, string>,
): Promise<Record<string, string>> {
  const aliases: Record<string, string> = {};
  for (const specifier of index.mockSpecifiers) {
    if (specifier.startsWith('next/')) {
      warnings.push(`Module mock "${specifier}" ignored: use mocks.next for Next.js APIs.`);
      continue;
    }
    const resolved = await resolveSpecifier(specifier, project.root);
    if (!resolved) {
      warnings.push(`Module mock "${specifier}" ignored: the specifier does not resolve from ${project.root}.`);
      continue;
    }
    if ((await readDirective(resolved)) === 'use server') {
      warnings.push(
        `Module mock "${specifier}" ignored: it is a 'use server' module. Server Actions run with story mocks applied, so mock the modules they call instead.`,
      );
      continue;
    }
    const names = new Set(await exportNames(resolved));
    // Keys used by mocks fill in names static analysis cannot see (CommonJS packages).
    const shimFile = path.join(shimDir, `${slug(specifier)}.ts`);
    const realImport = importPath(shimFile, resolved).replace(/\/index$/, '/index');
    const lines = [
      BANNER,
      `import * as real from ${JSON.stringify(realImport)};`,
      `import { createModuleMock } from 'rsc-stories/runtime/mock';`,
      '',
      `const mock = createModuleMock(${JSON.stringify(specifier)}, real as unknown as Record<string, unknown>);`,
    ];
    for (const name of [...names].sort()) {
      if (name === 'default') lines.push(`export default mock.get('default');`);
      else if (/^[A-Za-z_$][\w$]*$/.test(name))
        lines.push(`export const ${name} = mock.get(${JSON.stringify(name)}) as typeof real.${name};`);
    }
    if (names.size === 0) lines.push(`export default mock.get('default');`);
    await writeIfChanged(shimFile, lines.join('\n') + '\n');
    aliases[specifier] = shimFile;
    realFiles[resolved] = shimFile;
  }
  for (const [specifier, target] of Object.entries(project.config.aliases ?? {})) {
    aliases[specifier] = path.resolve(project.root, target);
  }
  return aliases;
}

/**
 * Writes the workshop's Next.js app into `.rsc-stories/.cache/workshop`: one canvas page and one
 * descriptor route per story file, the bridge components, and shims for Next APIs and mocked
 * modules. Only files whose content changed are touched, so a running `next dev` reloads minimally.
 */
export async function generateWorkshop(project: Project, index: StoryIndex, mode: RenderMode): Promise<GenerateResult> {
  const W = project.workshopDir;
  const warnings: string[] = [];
  const rsc = path.join(W, 'rsc');
  await mkdir(rsc, { recursive: true });
  const cacheComponents = hostUsesCacheComponents(project);

  // --- Next API shims -----------------------------------------------------------------------
  const shims = path.join(rsc, 'shims');
  await writeIfChanged(
    path.join(shims, 'next-headers.ts'),
    `${BANNER}import { cookies as realCookies } from 'next/dist/server/request/cookies';
import { headers as realHeaders } from 'next/dist/server/request/headers';
import { draftMode as realDraftMode } from 'next/dist/server/request/draft-mode';
import { createHeadersShim } from 'rsc-stories/runtime/mock';

const shim = createHeadersShim({
  cookies: realCookies as () => Promise<unknown>,
  headers: realHeaders as unknown as () => Promise<Headers>,
  draftMode: realDraftMode as () => Promise<unknown>,
});
export const cookies = shim.cookies as typeof realCookies;
export const headers = shim.headers as unknown as typeof realHeaders;
export const draftMode = shim.draftMode as typeof realDraftMode;
`,
  );
  for (const [file, source] of [
    ['next-navigation.server.ts', 'next/dist/client/components/navigation.react-server'],
    ['next-navigation.client.ts', 'next/dist/client/components/navigation'],
  ] as const) {
    await writeIfChanged(
      path.join(shims, file),
      `${BANNER}import * as real from '${source}';
import { createNavigationShim } from 'rsc-stories/runtime/mock';

export * from '${source}';
const shim = createNavigationShim(real as unknown as Parameters<typeof createNavigationShim>[0]);
export const redirect = shim.redirect as typeof real.redirect;
export const permanentRedirect = shim.permanentRedirect as typeof real.permanentRedirect;
export const notFound = shim.notFound as typeof real.notFound;
export const forbidden = shim.forbidden as typeof real.forbidden;
export const unauthorized = shim.unauthorized as typeof real.unauthorized;
`,
    );
  }
  const cacheNames = nextCacheExports(project).filter((name) => /^[A-Za-z_$][\w$]*$/.test(name));
  await writeIfChanged(
    path.join(shims, 'next-cache.ts'),
    `${BANNER}// @ts-ignore -- the CommonJS entry, imported by file so this alias does not apply to itself.
import * as real from 'next/cache.js';
import { createCacheShim } from 'rsc-stories/runtime/mock';

const shim = createCacheShim(real as unknown as Record<string, unknown>) as Record<string, any>;
${cacheNames.map((name) => `export const ${name} = shim.${name};`).join('\n')}
`,
  );

  // --- Mocked modules --------------------------------------------------------------------------
  const realFiles: Record<string, string> = {};
  const moduleAliases = await moduleShims(project, index, path.join(rsc, 'mocks'), warnings, realFiles);
  const aliases: Record<string, string> = {
    'next/headers': path.join(shims, 'next-headers.ts'),
    'next/dist/api/headers': path.join(shims, 'next-headers.ts'),
    'next/dist/api/navigation.react-server': path.join(shims, 'next-navigation.server.ts'),
    'next/dist/api/navigation': path.join(shims, 'next-navigation.client.ts'),
    'next/cache': path.join(shims, 'next-cache.ts'),
    ...moduleAliases,
  };

  // --- Client bridge ---------------------------------------------------------------------------
  const navigationPromises = hasNavigationPromisesContext(project);
  // Relative `./*.shared-runtime` requests are what Next's webpack config swaps for the server
  // layer's vendored contexts; importing Next's files by package path would give SSR a second
  // copy of each context. Turbopack and the browser just follow the re-export.
  for (const name of ['app-router-context', 'hooks-client-context']) {
    await writeIfChanged(
      path.join(rsc, 'contexts', `${name}.shared-runtime.ts`),
      `${BANNER}export * from 'next/dist/shared/lib/${name}.shared-runtime';\n`,
    );
  }
  await writeIfChanged(
    path.join(rsc, 'client.tsx'),
    `${BANNER}'use client';
import { useRouter } from 'next/navigation';
import { AppRouterContext } from './contexts/app-router-context.shared-runtime';
import {
  PathnameContext,
  SearchParamsContext,
  PathParamsContext,${navigationPromises ? '\n  NavigationPromisesContext,' : ''}
} from './contexts/hooks-client-context.shared-runtime';
import {
  CanvasBridgeImpl,
  createNavigationMock,
  type CanvasBridgeProps,
  type NavigationContexts,
} from 'rsc-stories/runtime/client';

export const NavigationMock = createNavigationMock({
  AppRouterContext,
  PathnameContext,
  SearchParamsContext,
  PathParamsContext,${navigationPromises ? '\n  NavigationPromisesContext,' : ''}
} as unknown as NavigationContexts);

export function CanvasBridge(props: Omit<CanvasBridgeProps, 'router'>) {
  const router = useRouter();
  return <CanvasBridgeImpl {...props} router={router} />;
}
`,
  );

  // --- Workshop runtime --------------------------------------------------------------------------
  const workshopFile = path.join(rsc, 'workshop.tsx');
  const imports: string[] = [];
  const previews: string[] = [];
  if (project.configFile && project.configHasRenderFields) {
    imports.push(`import * as config from ${JSON.stringify(importPath(workshopFile, project.configFile))};`);
  }
  if (project.previewFile) {
    imports.push(`import * as preview from ${JSON.stringify(importPath(workshopFile, project.previewFile))};`);
    previews.push('preview');
  }
  (project.config.addons ?? []).forEach((addon, i) => {
    if (!addon.preview) return;
    const file = path.resolve(project.root, addon.preview);
    imports.push(`import * as addon${i} from ${JSON.stringify(importPath(workshopFile, file))};`);
    previews.push(`addon${i}`);
  });
  await writeIfChanged(
    workshopFile,
    `${BANNER}import { connection } from 'next/server';
import { createWorkshop } from 'rsc-stories/runtime/server';
import { CanvasBridge, NavigationMock } from './client';
${imports.join('\n')}

export const workshop = createWorkshop({
  config: ${imports.some((line) => line.includes(' config ')) ? 'config' : 'undefined'},
  previews: [${previews.join(', ')}],
  mode: '${mode}',
  NavigationMock,
  CanvasBridge,
  connection,
});
`,
  );

  // --- Routes ------------------------------------------------------------------------------------
  const app = path.join(W, 'app');
  await writeIfChanged(
    path.join(app, 'layout.tsx'),
    `${BANNER}import type { ReactNode } from 'react';

export default function RootLayout({ children }: { children: ReactNode }) {
  return (
    <html lang="en" suppressHydrationWarning>
      <head>
        <script dangerouslySetInnerHTML={{ __html: 'window.__RSC_STORIES_CANVAS__ = true;' }} />
      </head>
      <body style={{ margin: 0 }}>{children}</body>
    </html>
  );
}
`,
  );
  const segmentConfig = cacheComponents ? '' : `\nexport const fetchCache = 'force-no-store';\n`;
  const canvasRoot = path.join(app, 'rsc-stories', 'canvas');
  const metaRoot = path.join(app, 'rsc-stories', 'meta');
  const keep = new Set<string>();
  for (const file of index.files) {
    if (file.error) continue;
    keep.add(file.fileKey);
    const info = JSON.stringify({
      fileKey: file.fileKey,
      componentId: file.componentId,
      title: file.title,
      path: file.relativePath,
    });
    const page = path.join(canvasRoot, file.fileKey, '[story]', '[state]', 'page.tsx');
    await writeIfChanged(
      page,
      `${BANNER}import * as stories from ${JSON.stringify(importPath(page, file.file))};
import { workshop } from ${JSON.stringify(importPath(page, workshopFile))};

const file = workshop.file(${info}, stories as Record<string, unknown>);
export default file.Page;
${segmentConfig}`,
    );
    const route = path.join(metaRoot, file.fileKey, 'route.ts');
    await writeIfChanged(
      route,
      `${BANNER}import * as stories from ${JSON.stringify(importPath(route, file.file))};
import { workshop } from ${JSON.stringify(importPath(route, workshopFile))};

export const GET = workshop.file(${info}, stories as Record<string, unknown>).GET;
`,
    );
  }
  for (const root of [canvasRoot, metaRoot]) {
    if (!existsSync(root)) continue;
    for (const entry of await readdir(root)) {
      if (!keep.has(entry)) await rm(path.join(root, entry), { recursive: true, force: true });
    }
  }
  await rm(path.join(rsc, 'mocks', '.rsc-stories-exports'), { recursive: true, force: true });

  // --- Config files ------------------------------------------------------------------------------
  let configChanged = false;
  const tsconfig = workshopTsconfig(project.tsconfig, W, project.root, project.next.major);
  configChanged = (await writeIfChanged(path.join(W, 'tsconfig.json'), JSON.stringify(tsconfig, null, 2) + '\n')) || configChanged;
  const postcss = ['postcss.config.mjs', 'postcss.config.js', 'postcss.config.cjs', '.postcssrc.json', '.postcssrc']
    .map((name) => path.join(project.root, name))
    .find((file) => existsSync(file));
  if (postcss) {
    const target = posix(path.relative(W, postcss));
    const load = /\.(c?js|mjs)$/.test(postcss)
      ? `import host from ${JSON.stringify(target.startsWith('.') ? target : `./${target}`)};`
      : `import { readFileSync } from 'node:fs';\nconst host = JSON.parse(readFileSync(new URL(${JSON.stringify(target)}, import.meta.url), 'utf8'));`;
    const tailwindV3Config = ['tailwind.config.ts', 'tailwind.config.js', 'tailwind.config.mjs', 'tailwind.config.cjs']
      .map((name) => path.join(project.root, name))
      .find((file) => existsSync(file));
    await writeIfChanged(
      path.join(W, 'postcss.config.mjs'),
      `${BANNER}${load}

// PostCSS runs with this directory as its working directory, but Tailwind finds class names (v4)
// or its config (v3) relative to the working directory: point it back at the host project.
const plugins = { ...(host.plugins ?? {}) };
if ('@tailwindcss/postcss' in plugins) {
  plugins['@tailwindcss/postcss'] = { base: ${JSON.stringify(project.root)}, ...(plugins['@tailwindcss/postcss'] ?? {}) };
}${
        tailwindV3Config
          ? `
if ('tailwindcss' in plugins) {
  plugins.tailwindcss = { config: ${JSON.stringify(tailwindV3Config)}, ...(plugins.tailwindcss ?? {}) };
}`
          : ''
      }

export default { ...host, plugins };
`,
    );
  }
  const options: WorkshopNextConfigOptions = {
    hostDir: project.root,
    workshopDir: W,
    ...(project.nextConfigFile ? { hostConfigFile: project.nextConfigFile } : {}),
    rootDir: project.rootDir,
    aliases,
    moduleShims: realFiles,
    bundler: project.bundler,
    nextMajor: project.next.major,
    phase: mode === 'dev' ? 'dev' : 'build',
    // Only `rsc-stories build` ends up on a static host, without Next's image optimizer.
    ...(mode === 'build' ? { staticExport: true } : {}),
  };
  configChanged =
    (await writeIfChanged(
      path.join(W, 'next.config.mjs'),
      `${BANNER}import { createWorkshopNextConfig } from 'rsc-stories/next-config';

export default createWorkshopNextConfig(${JSON.stringify(options, null, 2)});
`,
    )) || configChanged;
  // Next serves `public/` from its project directory; share the host's.
  const hostPublic = path.join(project.root, 'public');
  const workshopPublic = path.join(W, 'public');
  if (existsSync(hostPublic)) {
    const current = await lstat(workshopPublic).catch(() => undefined);
    if (!current) await symlink(hostPublic, workshopPublic, process.platform === 'win32' ? 'junction' : 'dir');
  }
  await writeIfChanged(
    path.join(W, 'package.json'),
    JSON.stringify({ name: 'rsc-stories-workshop', private: true, type: 'module' }, null, 2) + '\n',
  );
  return { aliases, warnings, configChanged };
}
